import os
import json
from unittest.mock import patch, MagicMock
from main import (
    _call_ai,
    _similarity_score,
    _deterministic_schema_mapping,
    analyze_schema,
    SchemaAnalyzeRequest,
    ai_plan,
    AIPlanRequest,
    ai_status,
    SessionLocal,
    DatasetModel
)

def test_ai_module():
    print("=" * 60)
    print("TESTING GEMINI / AI INTEGRATION AND DETERMINISTIC FALLBACK")
    print("=" * 60)

    # 1. Test similarity score
    s1 = _similarity_score("employee_id", "staff_code")
    s2 = _similarity_score("department", "department_name")
    s3 = _similarity_score("salary", "pay")
    s4 = _similarity_score("random_col", "another_col")
    print(f"Similarity scores: ID/Code={s1}, Dept={s2}, Salary/Pay={s3}, Random={s4}")
    assert s1 >= 0.6, "Failed synonym matching for ID"
    assert s2 >= 0.7, "Failed substring matching for Department"
    assert s3 >= 0.6, "Failed synonym matching for Salary"
    assert s4 == 0.0, "Unexpected match for unrelated columns"
    print("✓ Similarity scoring verified")

    # 2. Test deterministic schema mapping
    cols_a = ["employee_id", "employee_name", "department", "hire_date", "email"]
    cols_b = ["staff_code", "full_name", "department_name", "annual_salary", "bonus"]
    mappings = _deterministic_schema_mapping(cols_a, cols_b)
    print(f"Deterministic mappings generated: {len(mappings)}")
    for m in mappings:
        print(f"  {m['source_column']} -> {m['target_column']} (confidence={m['confidence']}, reason={m['reason']})")
    assert any(m["source_column"] == "employee_id" and m["target_column"] == "staff_code" for m in mappings)
    assert any(m["source_column"] == "department" and m["target_column"] == "department_name" for m in mappings)
    print("✓ Deterministic schema mapping verified")

    # 3. Test AI Status in Fallback mode
    st = ai_status()
    print("AI Status endpoint response:", st)
    assert st["ai_active"] is False
    assert st["status"] == "fallback_active"
    assert "deterministic" in st["provider"].lower()
    print("✓ AI status endpoint cleanly reflects fallback mode when no key set")

    # 4. Test Gemini live response parsing with mocked AI response
    mock_gemini_json = json.dumps({
        "mappings": [
            {
                "source_column": "employee_id",
                "target_column": "staff_code",
                "confidence": 0.98,
                "reason": "Both represent unique employee identification numbers across systems."
            },
            {
                "source_column": "department",
                "target_column": "department_name",
                "confidence": 0.95,
                "reason": "Department organizational unit names match."
            }
        ],
        "join_recommendation": "Join on employee_id = staff_code",
        "notes": "Semantic mapping successfully generated by Gemini 1.5 Flash."
    })

    with patch("main._call_ai", return_value=mock_gemini_json):
        # Create mock DB datasets if needed
        db = SessionLocal()
        ds_a = db.query(DatasetModel).filter(DatasetModel.original_filename == "employees.csv").first()
        ds_b = db.query(DatasetModel).filter(DatasetModel.original_filename == "payroll.csv").first()
        db.close()

        if ds_a and ds_b:
            res = analyze_schema(SchemaAnalyzeRequest(dataset_a_id=ds_a.id, dataset_b_id=ds_b.id))
            print("Mock Gemini Analyze Schema response:")
            print(f"  AI Generated: {res['ai_generated']}")
            print(f"  Mappings: {len(res['mappings'])}")
            print(f"  Join Rec: {res['join_recommendation']}")
            assert res["ai_generated"] is True
            assert len(res["mappings"]) == 2
            assert res["mappings"][0]["confidence"] == 0.98
            assert res["mappings"][0]["ai_generated"] is True
            print("✓ Gemini JSON response parsing & column validation verified")

    # 5. Test AI Plan generation with mocked AI response
    mock_plan_json = json.dumps({
        "summary": "AI Generated Pipeline: Merge employee master records with payroll compensation, deduplicate, and impute missing salaries.",
        "steps": [
            {
                "step": 1,
                "operation": "join",
                "description": "Inner join employee dataset with payroll dataset on employee_id = staff_code",
                "params": {"join_type": "inner", "left_key": "employee_id", "right_key": "staff_code"}
            },
            {
                "step": 2,
                "operation": "deduplicate",
                "description": "Drop duplicate records based on employee identifier",
                "params": {}
            },
            {
                "step": 3,
                "operation": "fill_missing",
                "description": "Impute missing annual salary values using department mean",
                "params": {"strategy": "mean_or_unknown"}
            }
        ],
        "join_key_recommendation": "employee_id",
        "warnings": ["Ensure tax rates are standardized before export"]
    })

    with patch("main._call_ai", return_value=mock_plan_json):
        if ds_a and ds_b:
            plan_res = ai_plan(AIPlanRequest(
                instruction="Combine employee and payroll, deduplicate and fill missing salaries",
                dataset_ids=[ds_a.id, ds_b.id]
            ))
            plan = plan_res["plan"]
            print("Mock Gemini AI Plan:")
            print(f"  AI Generated: {plan['ai_generated']}")
            print(f"  Summary: {plan['summary']}")
            print(f"  Steps: {len(plan['steps'])}")
            assert plan["ai_generated"] is True
            assert len(plan["steps"]) == 3
            assert plan["steps"][0]["operation"] == "join"
            print("✓ AI Plan generation & parsing verified")

    print("\n" + "=" * 60)
    print("ALL AI & DETERMINISTIC FALLBACK MODULE TESTS PASSED!")
    print("=" * 60)

if __name__ == "__main__":
    test_ai_module()
